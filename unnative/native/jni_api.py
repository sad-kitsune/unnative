# x86-64 System V return-register classes: integers and pointers come back in
# RAX, jfloat/jdouble in XMM0, void not at all. A Python-serviced stub uses this
# to place its synthesised return value.
_FLOAT_RETURNS = frozenset({"jfloat", "jdouble"})


def return_category(c_type: str) -> str:
    """-> "void" | "float" | "int" (int covers integers and pointers)."""
    t = c_type.strip()
    if t == "void":
        return "void"
    if t in _FLOAT_RETURNS:
        return "float"
    return "int"
