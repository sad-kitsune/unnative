"""Tests for the JNI tables, including a drift check against the system jni.h."""

from __future__ import annotations

import os
import re
import unittest

from unnative.native import jni_api


class ReturnCategoryTests(unittest.TestCase):
    def test_categories(self):
        self.assertEqual(jni_api.return_category("void"), "void")
        self.assertEqual(jni_api.return_category("jfloat"), "float")
        self.assertEqual(jni_api.return_category("jdouble"), "float")
        self.assertEqual(jni_api.return_category("jint"), "int")
        self.assertEqual(jni_api.return_category("jobject"), "int")   # pointer -> RAX
        self.assertEqual(jni_api.return_category("jmethodID"), "int")


class TableShapeTests(unittest.TestCase):
    def test_known_anchors(self):
        # First four JNIEnv slots are reserved; GetVersion is slot 4.
        self.assertEqual([s[1] for s in jni_api.JNIENV_SLOTS[:5]],
                         [None, None, None, None, "GetVersion"])
        self.assertEqual(jni_api.JNIENV_INDEX["GetVersion"], 4)
        for fn in ("FindClass", "GetMethodID", "GetStaticMethodID", "GetFieldID",
                   "RegisterNatives", "ExceptionCheck", "GetObjectClass"):
            self.assertIn(fn, jni_api.JNIENV_INDEX)
        # JavaVM: GetEnv is present (slot 6, after 3 reserved).
        self.assertEqual(jni_api.JAVAVM_INDEX["GetEnv"], 6)

    def test_counts(self):
        # 4 reserved + 230 functions (JNI through IsVirtualThread); "229+" per plan.
        named = [s for s in jni_api.JNIENV_SLOTS if s[1]]
        self.assertGreaterEqual(len(named), 229)
        self.assertEqual(len(jni_api.JAVAVM_SLOTS), 8)


_JNI_H = "/usr/lib/jvm/default/include/jni.h"


class DriftTests(unittest.TestCase):
    """Re-derive the tables from the real header and confirm the embedded copy is
    still correct (the data was generated by tools/gen_jni_api.py)."""

    def _parse(self, struct_name):
        if not os.path.exists(_JNI_H):
            raise unittest.SkipTest(f"{_JNI_H} not present")
        with open(_JNI_H) as f:
            H = f.read()
        body = re.search(r"struct %s \{(.*?)\n\};" % struct_name, H, re.S).group(1)
        slot = re.compile(r"^\s*(.*?)\(JNICALL \*([A-Za-z0-9_]+)\)", re.M)
        res = re.compile(r"^\s*void \*(reserved\d+);", re.M)
        out = []
        for line in body.splitlines():
            if res.match(line):
                out.append((None, "void*"))
            else:
                m = slot.match(line)
                if m:
                    out.append((m.group(2), m.group(1).strip()))
        return out

    def test_jnienv_matches_header(self):
        parsed = self._parse("JNINativeInterface_")
        embedded = [(name, ret) for _i, name, ret in jni_api.JNIENV_SLOTS]
        self.assertEqual(embedded, parsed)

    def test_javavm_matches_header(self):
        parsed = self._parse("JNIInvokeInterface_")
        embedded = [(name, ret) for _i, name, ret in jni_api.JAVAVM_SLOTS]
        self.assertEqual(embedded, parsed)


if __name__ == "__main__":
    unittest.main()
